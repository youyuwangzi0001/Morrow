// 生成创作台提示词内嵌包（构建期产物）。
//
// 安全模型（重要）：
//   创作台的方法论与工作流提示词（三套大师方法 + 提示词基座）是应用底层资产。
//   仓库里既不留明文 JSON，也不留可直接解密的密文——两者都能一键还原，等于没藏。
//
//   做法：产物写入 src/generated/（.gitignore 忽略，永不提交），只有本机构建时
//   用私有源数据现场生成；clone 仓库或拿源码包都得不到任何提示词内容。
//   私有源默认在 %APPDATA%\Morrow-build\prompts\，可用 MORROW_PROMPT_SOURCE 覆盖。
//
//   生成时再做一层轻量混淆（异或 + 分片重排），避免被顺手 strings 一眼看穿；
//   真正的保护是「不发布」，不是编码本身——写在这里防止后人误以为它是加密。
//
// Agent 侧的辅助提示词（侧边聊天、经验编辑、经验整理）不在内嵌范围，直接写在源码里。
//
// 用法：
//   node scripts/embed-prompts.mjs            生成 src/generated/prompts.bundle.ts
//   node scripts/embed-prompts.mjs --check    校验产物是否与源数据一致
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { gzipSync } from 'node:zlib'

const root = process.cwd()
const sourceDir = process.env.MORROW_PROMPT_SOURCE?.trim()
  || join(process.env.APPDATA?.trim() || join(homedir(), '.config'), 'Morrow-build', 'prompts')
const mastersPath = join(sourceDir, 'creative-masters.json')
const kitPath = join(sourceDir, 'prompt-kit.json')
const outPath = resolve(root, 'src', 'generated', 'prompts.bundle.ts')
const checkOnly = process.argv.includes('--check')
// --placeholder-ok：缺私有源时写空占位并视为成功（只给 typecheck 用）。
// 生成失败（源数据损坏等）仍然是错误，不能吞掉。
const placeholderOk = process.argv.includes('--placeholder-ok')

// 混淆参数：固定值只为可复现，不承担保密职责（与运行时解码保持一致）
const XOR_KEY = 0x5a

/**
 * 轻量混淆：gzip 字节 → 逐字节异或 → 整体倒序。
 *
 * 两个步骤都可逆，且不依赖分片长度，避免「末尾不足一整片」时拼接错位。
 * 它只让产物不能被 strings 一眼看穿，真正的保护是产物不进仓库。
 */
export function scramble(bytes) {
  const out = Buffer.from(bytes)
  for (let index = 0; index < out.length; index++) out[index] ^= XOR_KEY
  return out.reverse()
}

if (!existsSync(mastersPath) || !existsSync(kitPath)) {
  const missing = [mastersPath, kitPath].filter((path) => !existsSync(path))
  if (existsSync(outPath) && checkOnly) {
    console.log('提示词内嵌包：未找到私有源数据，沿用已生成的构建产物')
    process.exit(0)
  }
  // 没有私有源、也没有现成产物时，写一个只满足类型检查的空占位。
  // 它不是"没有提示词的降级版"——PROMPTS_BUNDLE 为空串，decodeBundle() 会立刻
  // 在 gunzip 处抛错。CI 的 typecheck 只需要该模块存在；任何真正调用提示词的
  // 构建（npm run build / dist）都会先跑 prebuild 重新生成，缺私有源时明确失败。
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(
    outPath,
    [
      '// AUTO-GENERATED placeholder by scripts/embed-prompts.mjs.',
      '// 本机缺少提示词私有源数据时生成，仅供 typecheck 通过；运行时解码会直接抛错。',
      `// 缺失：${missing.join(', ')}`,
      'export const PROMPTS_BUNDLE = \'\'',
      ''
    ].join('\n')
  )
  console.error('缺少提示词私有源数据：')
  for (const path of missing) console.error(`  ${path}`)
  console.error('已写入空占位 src/generated/prompts.bundle.ts（仅供类型检查）。')
  console.error('这些文件不进仓库、也不随应用或源码包分发；正式构建前需在本机准备。')
  console.error('打包会明确失败，而不是静默产出缺少提示词的构建。')
  process.exit(placeholderOk ? 0 : 1)
}

const masters = JSON.parse(readFileSync(mastersPath, 'utf8'))
const kit = JSON.parse(readFileSync(kitPath, 'utf8'))
const payload = JSON.stringify({ version: 2, masters: masters.masters ?? masters, kit })
const packed = scramble(gzipSync(Buffer.from(payload, 'utf8'), { level: 9 })).toString('base64')

const counts = {
  suites: Object.keys(masters.masters ?? masters),
  systemPrompts: Object.keys(kit.systemPrompts ?? {}).length,
  v4Lines: Object.keys(kit.v4?.lines ?? {}).length,
  handTemplates: Object.keys(kit.hand?.templates ?? {}).length,
  instruments: Object.keys(kit.music?.palette ?? {}).length
}
const header = [
  '// AUTO-GENERATED by scripts/embed-prompts.mjs. 构建期产物，不提交、不随源码分发。',
  '// 创作台提示词（三套大师方法 + 提示词基座）的唯一运行时来源。',
  `// ${JSON.stringify({ ...counts, plainBytes: Buffer.byteLength(payload) })}`,
  ''
].join('\n')
const output = `${header}export const PROMPTS_BUNDLE = '${packed}'\n`

if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  if (current !== output) {
    console.error('src/generated/prompts.bundle.ts 与私有源数据不一致：请运行 node scripts/embed-prompts.mjs')
    process.exit(1)
  }
  console.log('提示词内嵌包：构建产物与源数据一致')
  process.exit(0)
}

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, output)
console.log(`提示词内嵌包已生成：${Buffer.byteLength(payload)} B 明文 → ${packed.length} B 产物`)
console.log(`  三套大师方法：${counts.suites.join(' / ')}`)
console.log(`  系统提示词 ${counts.systemPrompts} 条 · 骨架固定句 ${counts.v4Lines} 条 · 手部模板 ${counts.handTemplates} 条 · 乐器 ${counts.instruments} 组`)
console.log('  产物位置：src/generated/（不进仓库、不进源码包）')