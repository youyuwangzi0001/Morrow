export interface BuiltinSkill {
  name: string
  description: string
  /** SKILL.md 全文（frontmatter + 正文） */
  content: string
}

function skill(name: string, description: string, body: string): BuiltinSkill {
  return {
    name,
    description,
    content: `---\nname: ${name}\ndescription: ${description}\n---\n\n${body.trim()}\n`
  }
}

